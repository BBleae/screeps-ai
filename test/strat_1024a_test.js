const fs = require('fs');
const vm = require('vm');
const src = fs.readFileSync(__dirname + '/../src/main.js', 'utf8');
const a = src.indexOf('const SPIKE_LINE');
const b = src.indexOf('function spkRoleDigest');
const c = src.indexOf('\n}\n', b) + 3;
let fail = 0;
const assert = (k, m) => { if (k) console.log('✓', m); else { fail++; console.log('✗ FAIL:', m); } };
function make(used, seg91) {
    const ctx = { Game: { time: 1000, cpu: { getUsed: () => used, bucket: 9900 }, creeps: { a: 1 } }, Memory: {}, RawMemory: { segments: {}, setActiveSegments() {} }, segMem: { activeIds: () => [90, 91] }, JSON, Math, Object, Array, Number };
    if (seg91 !== undefined) ctx.RawMemory.segments[91] = seg91;
    vm.createContext(ctx);
    vm.runInContext(src.slice(a, c) + '\nthis.noteSpike=noteSpike;this.setTick=(o)=>{spkTick=o};', ctx);
    return ctx;
}
let x = make(200, JSON.stringify({ spikes: [{ t: 1 }], at: 5 }));
x.setTick({ creeps: 90, spawn: 40, 'move.end': 15, assess: 8, remote: 5, conquest: 2, layout: 1.5 });
x.noteSpike(0);
let s = JSON.parse(x.RawMemory.segments[91]);
assert(s.big.length === 1 && s.big[0].cpu === 200, '>190 记一条 big');
assert(s.big[0].top.length === 5 && s.big[0].top[0][0] === 'creeps' && s.big[0].top[4][0] === 'remote', 'top 5 模块按耗时降序');
assert(s.spikes.length === 1 && s.at === 5, '原 spikes 不丢');
assert(x.Memory.cpuSpikes.length === 1, '>150 照旧进 Memory.cpuSpikes');
x = make(180, JSON.stringify({ spikes: [], at: 5 }));
x.setTick({ creeps: 90 });
x.noteSpike(0);
assert(!JSON.parse(x.RawMemory.segments[91]).big, '≤190 不记 big');
const old = []; for (let i = 0; i < 25; i++) old.push({ t: i, cpu: 191 });
x = make(195, JSON.stringify({ spikes: [], at: 5, big: old }));
x.setTick({ creeps: 90 });
x.noteSpike(0);
s = JSON.parse(x.RawMemory.segments[91]);
assert(s.big.length === 20 && s.big[19].cpu === 195 && s.big[0].t === 6, 'big 只留最近 20 条');
x = make(200);
x.setTick({ creeps: 90 });
x.noteSpike(0);
assert(x.RawMemory.segments[91] === undefined, '段没加载时不写，避免冲掉旧记录');
x = make(200, JSON.stringify({ spikes: [], at: 5, big: [{ t: 9 }] }));
x.setTick({ creeps: 90 });
x.Memory.cpuSpikes = [1, 2, 3, 4, 5, 6, 7, 8];
x.noteSpike(0);
s = JSON.parse(x.RawMemory.segments[91]);
assert(s.big.length === 2 && s.spikes.length === 1, 'Memory 溢出写段时保留 big');
console.log(fail ? fail + ' FAIL' : 'ALL PASS');
process.exit(fail ? 1 : 0);
